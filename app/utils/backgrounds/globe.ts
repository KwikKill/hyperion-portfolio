// Point of the unit sphere for a latitude and longitude
export function unit([lat, lon]: [number, number]): [number, number, number] {
  const cl = Math.cos(lat * DEG);
  return [cl * Math.sin(lon * DEG), Math.sin(lat * DEG), cl * Math.cos(lon * DEG)];
}
